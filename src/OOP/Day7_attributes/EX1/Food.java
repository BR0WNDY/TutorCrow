package OOP.Day7_attributes.EX1;

public class Food {
    String name;
    int price;
    String restaurant;
    boolean isAvaliable;

    public Food (String name,int price , String restaurant, boolean isAvaliable){
        this.name = name;
        this.price = price;
        this.restaurant = restaurant;
        this.isAvaliable = isAvaliable;
    }
}
