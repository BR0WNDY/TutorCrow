package Lesson1;

public class L1_Variables {
    public static void main() {
        // Basic of printing
        System.out.println("Hi\n Hello World");
        System.out.println("Hello");

        // Variables (Numbers,boolean string)
        //Numbers (int float double long)
        int myNumbers = 12;
        System.out.println(myNumbers);
        // use long for very long numbers
        long myLongNumber = 1234567891234546789L;
        System.out.println(myLongNumber);

        // Decimals (Double and Float)
        double myDecimalNumber = 3.14;
        System.out.println(myDecimalNumber);

        float myFloatNumber = 3.14F;
        System.out.println(myFloatNumber);

        //most important = int and double

        //boolean (variable names should start with is / has / have
        boolean isDog = false;
        boolean hasPhone = true;
        System.out.println(isDog);
        System.out.println(hasPhone);

        // String
        String myName = "Boom";
        System.out.println(myName);
        System.out.println("My Name is "+ myName);



    }
}

